import assert from 'node:assert/strict'

export async function verifyCatalog({ send, evaluate, fill, click, screenshot, navigate, until, browserAPI, companyId, results }) {
  const endpoint = resource => `companies/${companyId}/erp/${resource}/`
  async function ready() { await until(() => evaluate('!document.querySelector(".loading-state") && Boolean(document.querySelector(".control-panel"))'), 'catalog data') }
  async function button(text, selector = '.control-actions button') {
    await evaluate(`(() => { const button = [...document.querySelectorAll(${JSON.stringify(selector)})].find(el => el.textContent.trim() === ${JSON.stringify(text)}); if (!button) throw new Error('Missing ' + ${JSON.stringify(text)}); button.click(); })()`)
  }
  async function openNew() { await button('New'); await until(() => evaluate('Boolean(document.querySelector("dialog[open] fieldset:not(:disabled)"))'), 'catalog editor') }
  async function save() { await click('dialog[open] .dialog-footer .button-primary'); await until(() => evaluate('!document.querySelector("dialog[open]") && !document.querySelector(".loading-state")'), 'saved catalog record') }
  async function openImport() { await button('Import'); await until(() => evaluate('Boolean(document.querySelector(".import-dialog[open]"))'), 'import dialog') }
  async function csvFile(text) {
    await evaluate(`(() => { const transfer = new DataTransfer(); transfer.items.add(new File([${JSON.stringify(text)}], 'catalog.csv', { type: 'text/csv' })); const input = document.querySelector('dialog[open] input[type=file]'); input.files = transfer.files; input.dispatchEvent(new Event('change', { bubbles: true })); })()`)
    await until(() => evaluate(`document.querySelector('textarea[name=csv_contents]').value === ${JSON.stringify(text)}`), 'CSV file contents')
  }
  async function preview() { await button('Preview CSV', 'dialog[open] button'); await until(() => evaluate('Boolean(document.querySelector(".import-preview")) && !document.querySelector("dialog[open] button[type=submit]").disabled'), 'CSV preview') }
  await send('Emulation.setDeviceMetricsOverride', { width: 1365, height: 900, deviceScaleFactor: 1, mobile: false })
  await navigate('/contacts'); await ready(); await openNew()
  await fill('dialog[open] input[name=name]', 'Catalog phase customer')
  await fill('dialog[open] input[name=phone]', '009987654')
  await save(); await openNew()
  await fill('dialog[open] input[name=name]', 'Catalog phase supplier')
  await click('dialog[open] input[name=is_customer]'); await click('dialog[open] input[name=is_supplier]')
  await save()
  await fill('input[aria-label="Search Contacts"]', 'Catalog phase')
  await until(() => evaluate('document.querySelectorAll(".record-card").length === 2'), 'filtered contacts')
  await fill('select[aria-label="Contact role"]', 'supplier')
  await until(() => evaluate('document.querySelectorAll(".record-card").length === 1 && document.querySelector(".record-card h2").textContent.includes("supplier")'), 'supplier role filter')
  await fill('select[aria-label="Contact role"]', 'all')
  await fill('input[aria-label="Search Contacts"]', '009987654')
  await until(() => evaluate('document.querySelectorAll(".record-card").length === 1 && document.querySelector(".record-card h2").textContent.includes("customer")'), 'phone search')
  await click('.record-card-main')
  await until(() => evaluate('Boolean(document.querySelector("dialog[open] fieldset:not(:disabled)"))'), 'existing contact form')
  await fill('dialog[open] input[name=phone]', '009987655')
  await evaluate('window.__originalCatalogConfirm = window.confirm; window.confirm = () => false')
  await click('dialog[open] button[aria-label=Close]')
  assert.equal(await evaluate('Boolean(document.querySelector("dialog[open]"))'), true)
  await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  assert.equal(await evaluate('Boolean(document.querySelector("dialog[open]"))'), true)
  await save()
  assert.equal(await evaluate('Boolean(document.activeElement?.closest("dialog"))'), false)
  await evaluate('window.confirm = window.__originalCatalogConfirm')
  results.push('Shared catalog fields and dialogs preserve contact edits; customer/supplier filters and phone search work.')

  await openImport()
  await csvFile('name,is_customer\nInvalid contact,maybe\n')
  await preview()
  assert.equal(await evaluate('[...document.querySelectorAll("dialog[open] button")].find(el => el.textContent.trim() === "Import records").disabled'), true)
  assert.equal((await browserAPI(endpoint('contacts') + '?q=Invalid%20contact')).data.count, 0)
  const contactCsv = 'name,email,is_customer,is_supplier,notes\n"Catalog phase imported, person",imported@example.test,true,false,"First line\nSecond line"\n'
  await csvFile(contactCsv); await preview()
  await button('Import records', 'dialog[open] button')
  await until(() => evaluate('!document.querySelector("dialog[open]") && document.querySelector(".notice.success")?.textContent.includes("1 records imported")'), 'CSV contact import')
  const imported = (await browserAPI(endpoint('contacts') + '?q=imported%40example.test')).data.results[0]
  assert.equal(imported.notes, 'First line\nSecond line')
  await fill('input[aria-label="Search Contacts"]', 'Catalog phase')
  await until(() => evaluate('document.querySelectorAll(".record-card").length === 3'), 'three phase contacts')
  await fill('select[aria-label="Sort records"]', 'name'); await ready()
  await click('button[aria-label="List view"]'); await ready()
  assert.equal(await evaluate('document.querySelectorAll(".data-table tbody tr").length'), 3)
  await click('.data-table thead .sort-button'); await ready()
  assert.equal(await evaluate('document.querySelector(".data-table th[aria-sort]").getAttribute("aria-sort")'), 'descending')
  await evaluate('window.__originalCatalogConfirm = window.confirm; window.confirm = () => false')
  await click('.selection-bar input[type=checkbox]')
  await button('Archive selected', '.selection-bar button')
  assert.equal((await browserAPI(endpoint('contacts') + '?q=Catalog%20phase')).data.count, 3)
  await evaluate('window.confirm = () => true')
  await button('Archive selected', '.selection-bar button')
  await until(() => evaluate('Boolean(document.querySelector(".empty-state")) && !document.querySelector(".loading-state")'), 'archived selection')
  await fill('select[aria-label="Active records"]', 'false'); await ready()
  await until(() => evaluate('document.querySelectorAll(".data-table tbody tr").length === 3'), 'archived contacts')
  await click('.selection-bar input[type=checkbox]')
  await button('Restore selected', '.selection-bar button')
  await until(() => evaluate('Boolean(document.querySelector(".empty-state")) && !document.querySelector(".loading-state")'), 'restored selection')
  await evaluate('window.confirm = window.__originalCatalogConfirm')
  results.push('CSV import validates every row and quoted multiline text; sorted lists support confirmed bulk archive and restore.')

  await navigate('/inventory'); await ready()
  await button('Categories')
  await fill('input[name=category_name]', 'Catalog phase office')
  await button('Add category', 'dialog[open] button')
  await until(() => evaluate('document.querySelector(".category-list")?.textContent.includes("Catalog phase office") && !document.querySelector("input[name=category_name]").disabled'), 'new category')
  await button('Close', 'dialog[open] .dialog-footer button')
  const category = (await browserAPI(endpoint('product-categories'))).data.results.find(item => item.name === 'Catalog phase office')
  await openNew()
  await fill('dialog[open] input[name=name]', 'Catalog phase cabinet')
  await fill('dialog[open] input[name=sku]', 'CAT-CABINET')
  await fill('dialog[open] input[name=barcode]', '00001122')
  await fill('dialog[open] input[name=sale_price]', '125')
  await fill('dialog[open] select[name=category_id]', String(category.id))
  await save()
  assert.equal((await browserAPI(endpoint('products') + '?q=00001122')).data.results[0].barcode, '00001122')
  await openImport()
  await csvFile('name,sku,category,barcode,kind,sale_price\nCatalog phase imported box,CAT-BOX,Catalog phase office,00002233,goods,20\nCatalog phase service,CAT-SERVICE,Catalog phase office,,service,50\n')
  await preview(); await button('Import records', 'dialog[open] button')
  await until(() => evaluate('!document.querySelector("dialog[open]") && document.querySelector(".notice.success")?.textContent.includes("2 records imported")'), 'product import')
  await fill('select[aria-label="Product category"]', String(category.id)); await ready()
  await until(() => evaluate('document.querySelectorAll(".record-card").length === 3'), 'category filter')
  await fill('select[aria-label="Stock availability"]', 'out'); await ready()
  await until(() => evaluate('document.querySelectorAll(".record-card").length === 2'), 'stock filter excludes service')
  await fill('select[aria-label="Product type"]', 'service'); await ready()
  await until(() => evaluate('Boolean(document.querySelector(".empty-state"))'), 'combined filters empty state')
  await button('Clear filters', '.catalog-filters button'); await ready()
  results.push('Products support company categories, leading-zero barcodes, CSV creation, and combined category/type/stock filters.')

  await button('Categories')
  await until(() => evaluate('document.querySelector(".category-list")?.textContent.includes("Catalog phase office")'), 'category list')
  await button('Archive', '.category-list button')
  await until(() => evaluate('document.querySelector(".category-list")?.textContent.includes("Archived") && !document.querySelector("input[name=category_name]").disabled'), 'archived category')
  await button('Close', 'dialog[open] .dialog-footer button')
  await fill('input[aria-label="Search Products"]', '00001122')
  await until(() => evaluate('document.querySelectorAll(".record-card").length === 1'), 'barcode search')
  await click('.record-card-main')
  await until(() => evaluate('Boolean(document.querySelector("select[name=category_id] option:checked:disabled"))'), 'retained archived category')
  await fill('dialog[open] input[name=name]', 'Catalog phase cabinet updated'); await save()
  assert.equal((await browserAPI(endpoint('products') + '?q=00001122')).data.results[0].category_id, category.id)
  await screenshot('catalog-products-desktop.png')
  results.push('Archived product categories remain visible on existing products and ordinary edits preserve the relationship.')

  await send('Browser.setDownloadBehavior', { behavior: 'deny' })
  await evaluate('window.__catalogDownloads = []; window.__catalogCreateURL = URL.createObjectURL; URL.createObjectURL = blob => { window.__catalogDownloads.push(blob); return window.__catalogCreateURL(blob) }')
  await button('Export CSV')
  await until(() => evaluate('window.__catalogDownloads.length === 1'), 'export download')
  const exported = await evaluate('window.__catalogDownloads[0].text()')
  assert.match(exported, /CAT-CABINET/)
  assert.match(exported, /00001122/)
  assert.doesNotMatch(exported, /CAT-BOX/)
  assert.deepEqual(await evaluate('(async () => [...new Uint8Array(await window.__catalogDownloads[0].arrayBuffer()).slice(0, 3)])()'), [239, 187, 191])
  await openImport(); await button('Download CSV template', 'dialog[open] button')
  await until(() => evaluate('window.__catalogDownloads.length === 2'), 'CSV template download')
  assert.match(await evaluate('window.__catalogDownloads[1].text()'), /"category","barcode"/)
  await button('Discard', 'dialog[open] .dialog-footer button')
  await send('Emulation.setDeviceMetricsOverride', { width: 375, height: 812, deviceScaleFactor: 1, mobile: true })
  assert.equal(await evaluate('document.documentElement.scrollWidth <= window.innerWidth'), true)
  await openNew()
  assert.equal(await evaluate('document.querySelector("dialog[open]").scrollWidth <= document.querySelector("dialog[open]").clientWidth'), true)
  await evaluate('document.querySelector("dialog[open] button[aria-label=Close]").focus()')
  await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9, modifiers: 8 })
  await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9, modifiers: 8 })
  assert.equal(await evaluate('document.activeElement.textContent.trim()'), 'Discard')
  for (let index = 0; index < 20; index++) {
    await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9 })
    await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9 })
    assert.equal(await evaluate('Boolean(document.activeElement?.closest("dialog[open]"))'), true, `Tab ${index}: ${await evaluate('document.activeElement?.outerHTML.slice(0, 200)')}`)
  }
  await screenshot('catalog-product-form-mobile.png')
  await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await until(() => evaluate('!document.querySelector("dialog[open]")'), 'Escape closes clean dialog')
  await navigate('/contacts'); await ready()
  assert.equal(await evaluate('document.documentElement.scrollWidth <= window.innerWidth'), true)
  await screenshot('catalog-contacts-mobile.png')
  await send('Emulation.setDeviceMetricsOverride', { width: 1365, height: 900, deviceScaleFactor: 1, mobile: false })
  results.push('Filtered CSV export and templates create UTF-8 downloads; catalog forms fit 375px and support Escape and Tab/Shift+Tab focus wrapping.')
}

export async function verifyCatalogReadOnly({ evaluate, click, navigate, until, results }) {
  for (const route of ['/contacts', '/inventory']) {
    await navigate(route)
    await until(() => evaluate('Boolean(document.querySelector(".record-card")) && !document.querySelector(".loading-state")'), 'read-only catalog')
    assert.equal(await evaluate('document.querySelectorAll(".selection-bar, .card-selection, .control-actions .button-primary").length'), 0)
    assert.equal(await evaluate('[...document.querySelectorAll(".control-actions button")].some(el => el.textContent.trim() === "Import")'), false)
    await click('.record-card-main')
    await until(() => evaluate('Boolean(document.querySelector("dialog[open] fieldset:disabled"))'), 'read-only catalog form')
    assert.equal(await evaluate('Boolean(document.querySelector("dialog[open] button[type=submit]"))'), false)
    await click('dialog[open] button[aria-label=Close]')
  }
  results.push('Company members can view Contacts and Products but have no editor, import, selection or bulk-write controls.')
}
